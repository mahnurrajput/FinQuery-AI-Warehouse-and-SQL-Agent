--------------------------------------------------------------------
-- 1. INDEXING
--------------------------------------------------------------------

-- 1a. B-Tree index on date_key
-- =====================================================================
-- Justification: B-Tree range scan optimization. Nearly every query 
-- filters or groups through dim_date. Date ranges are highly selective 
-- (e.g., selecting 1 year out of 10), allowing the query planner to 
-- favor an Index Scan or Bitmap Index Scan over a full table scan.
DROP INDEX IF EXISTS dw_etl.idx_fact_transactions_date_key;
CREATE INDEX idx_fact_transactions_date_key
ON dw_etl.fact_transactions USING btree (date_key);

-- Test B-Tree index performance
EXPLAIN ANALYZE
SELECT COUNT(*) AS num_transactions
FROM dw_etl.fact_transactions f
JOIN dw_etl.dim_date d ON f.date_key = d.date_key
WHERE d.full_date BETWEEN '2013-01-01' AND '2013-12-31';


-- 1b. B-Tree index on customer_key
-- =====================================================================
-- Justification: Point-lookup acceleration. Accelerates highly selective 
-- queries filtering by individual customer (e.g., WHERE customer_key = 1001). 
-- Note: Does NOT optimize full-table customer aggregations/rankings without 
-- filters, where PostgreSQL naturally defaults to a sequential scan + hash aggregate.
DROP INDEX IF EXISTS dw_etl.idx_fact_transactions_customer_key;
CREATE INDEX idx_fact_transactions_customer_key
ON dw_etl.fact_transactions USING btree (customer_key);

-- Test index performance
EXPLAIN ANALYZE
SELECT customer_key, ROUND(SUM(amount), 2) AS total_spent
FROM dw_etl.fact_transactions
WHERE customer_key = 1001
GROUP BY customer_key;


-- 1c. Partial index on fraud_label = TRUE
-- =====================================================================
-- Justification: Specialized partial filtering. Fraud accounts for a tiny 
-- fraction of all records. This compact partial index speeds up queries 
-- filtering strictly for fraudulent activity (e.g., WHERE fraud_label = TRUE). 
-- Note: Queries calculating overall fraud rates (which count both TRUE and 
-- FALSE rows) will perform sequential scans as both populations are required.
DROP INDEX IF EXISTS dw_etl.idx_fact_transactions_fraud_true;
CREATE INDEX idx_fact_transactions_fraud_true
ON dw_etl.fact_transactions (fraud_label)
WHERE fraud_label = TRUE;

-- Test index performance
EXPLAIN ANALYZE
SELECT COUNT(*) AS num_frauds
FROM dw_etl.fact_transactions
WHERE fraud_label = TRUE;


-- 1d. B-Tree index on location_key
-- =====================================================================
-- Justification: Foreign Key join & dimension filtering. City/state 
-- filtering occurs on dim_location first (e.g., WHERE merchant_state = 'CA'). 
-- This index enables nested loop / hash joins from selective dim_location 
-- keys directly into fact_transactions without scanning unrelated facts.
DROP INDEX IF EXISTS dw_etl.idx_fact_transactions_location_key;
CREATE INDEX idx_fact_transactions_location_key
ON dw_etl.fact_transactions USING btree (location_key);

-- Test index performance
EXPLAIN ANALYZE
SELECT loc.merchant_state, COUNT(*) AS num_transactions
FROM dw_etl.fact_transactions f
JOIN dw_etl.dim_location loc ON f.location_key = loc.location_key
WHERE loc.merchant_state = 'CA'
GROUP BY loc.merchant_state;


-- 1e. B-Tree index on card_key (NEW - NL-to-SQL Agent Workload)
-- =====================================================================
-- Justification: Ad-hoc query optimization for GenAI/LLM layer. 
-- The fixed BI dashboard does not perform selective lookups on cards, 
-- but the NL-to-SQL agent frequently executes point lookups or card-level 
-- histories (e.g., "Show recent transactions for card ID X").
DROP INDEX IF EXISTS dw_etl.idx_fact_transactions_card_key;
CREATE INDEX idx_fact_transactions_card_key
ON dw_etl.fact_transactions USING btree (card_key);

-- Test index performance
EXPLAIN ANALYZE
SELECT transaction_id, amount, date_key
FROM dw_etl.fact_transactions
WHERE card_key = 500
ORDER BY date_key DESC;


-- 1f. B-Tree index on mcc_key (NEW - NL-to-SQL Agent Workload)
-- =====================================================================
-- Justification: Ad-hoc query optimization for GenAI/LLM layer. 
-- Supports dynamic merchant category code filtering generated by the LLM 
-- agent (e.g., "Find all grocery store transactions [MCC 5411] in 2018").
DROP INDEX IF EXISTS dw_etl.idx_fact_transactions_mcc_key;
CREATE INDEX idx_fact_transactions_mcc_key
ON dw_etl.fact_transactions USING btree (mcc_key);

-- Test index performance
EXPLAIN ANALYZE
SELECT COUNT(*), SUM(amount)
FROM dw_etl.fact_transactions
WHERE mcc_key = 12
GROUP BY mcc_key;


--------------------------------------------------------------------
-- 2. MATERIALIZED VIEW
--------------------------------------------------------------------
-- Justification: DSS aggregation caching. Precomputes a heavy 3-way join 
-- and group-by (Year, Month, State) not captured in static MOLAP tables.
-- Eliminates fact-table scans for interactive monthly geospatial fraud reporting.

DROP MATERIALIZED VIEW IF EXISTS dw_etl.mv_monthly_fraud_summary;

CREATE MATERIALIZED VIEW dw_etl.mv_monthly_fraud_summary AS
SELECT
    d.year,
    d.month,
    loc.merchant_state,
    COUNT(*) AS num_transactions,
    SUM(CASE WHEN f.fraud_label THEN 1 ELSE 0 END) AS num_frauds,
    SUM(f.amount) AS total_amount
FROM dw_etl.fact_transactions f
JOIN dw_etl.dim_date d ON f.date_key = d.date_key
JOIN dw_etl.dim_location loc ON f.location_key = loc.location_key
GROUP BY d.year, d.month, loc.merchant_state
ORDER BY d.year, d.month, loc.merchant_state;

-- Unique index required for non-blocking concurrent refreshes
CREATE UNIQUE INDEX idx_mv_monthly_fraud_summary_uniq
ON dw_etl.mv_monthly_fraud_summary (year, month, merchant_state);

-- Test query on materialized view
EXPLAIN ANALYZE
SELECT *
FROM dw_etl.mv_monthly_fraud_summary
WHERE merchant_state = 'CA'
ORDER BY year, month;


