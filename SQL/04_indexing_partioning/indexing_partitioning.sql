-- 3. PARTITIONING
--------------------------------------------------------------------
-- Rationale: Range partitioning on full_date (2010–2019 + DEFAULT) to 
-- enable Partition Pruning during time-bounded queries.
--
-- NOTE: dw_etl.partitioned_fact_transactions is a standalone benchmark/demo 
-- copy used to evaluate pruning performance against dw_etl.fact_transactions. 
-- Production writes land on dw_etl.fact_transactions via etl.sql.

-- 1. Create parent table WITHOUT the PK/UNIQUE constraints for now
DROP TABLE IF EXISTS dw_etl.partitioned_fact_transactions CASCADE;

CREATE TABLE dw_etl.partitioned_fact_transactions (
    fact_id         BIGSERIAL,
    transaction_id  BIGINT NOT NULL,
    full_date       DATE NOT NULL,
    customer_key    BIGINT REFERENCES dw_etl.dim_customer(customer_key),
    card_key        BIGINT REFERENCES dw_etl.dim_card(card_key),
    merchant_key    BIGINT REFERENCES dw_etl.dim_merchant(merchant_key),
    location_key    BIGINT REFERENCES dw_etl.dim_location(location_key),
    mcc_key         BIGINT REFERENCES dw_etl.dim_mcc(mcc_key),
    amount          NUMERIC(18,2),
    use_chip        BOOLEAN,
    fraud_label     BOOLEAN,
    anomaly_flag    BOOLEAN DEFAULT FALSE,
    error_key       BIGINT REFERENCES dw_etl.dim_error(error_key)
) PARTITION BY RANGE (full_date);

